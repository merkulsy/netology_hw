"""
Используя стек из задания 1, решите задачу на проверку сбалансированности скобок. Сбалансированность скобок означает,
что каждый открывающий символ имеет соответствующий ему закрывающий, и пары скобок правильно вложены друг в друга.
Пример сбалансированных последовательностей скобок:
(((([{}]))))
[([])((([[[]]])))]{()}
{{[()]}}
Несбалансированные последовательности:
}{}
{{[(])]}}
[[{())}]
Программа ожидает на вход строку со скобками.
На выход сообщение: «Сбалансированно», если строка корректная, и «Несбалансированно», если строка составлена неверно.
"""

from hw1_stack import Stack

def is_balanced(text: str) -> bool:
    """
    Проверяет, сбалансированы ли скобки в строке.
    Учитываются три вида скобок: (), [], {}.
    Все остальные символы игнорируются.
    """
    stack = Stack()
    opening = "([{"
    closing = ")]}"
    pairs = {')': '(', ']': '[', '}': '{'}   # соответствие закрывающей → открывающей

    for ch in text:                          # перебираем все символы строки
        if ch in opening:                    # если это открывающая скобка
            stack.push(ch)                   # кладём её на стек (ждём закрывающую)
        elif ch in closing:                  # если это закрывающая скобка
            # если стек пуст — значит закрывающая скобка не имеет пары
            if stack.is_empty():
                return "Unbalanced"
            # снимаем верхнюю открывающую скобку
            top = stack.pop()
            # проверяем, соответствует ли она текущей закрывающей
            if top != pairs[ch]:
                return "Unbalanced"                 # не совпадают → неправильный порядок
        # остальные символы (буквы, цифры, знаки) просто игнорируем

    # Если после обработки всех символов стек пуст — все скобки закрыты правильно
    if stack.is_empty():
        return "Balanced"
    else:
        return "Unbalanced"

"""
Пошаговое объяснение
if ch in opening – если текущий символ – одна из открывающих скобок (, [ или {, мы помещаем её в стек. 
Стек хранит все открывающие скобки, которые мы встретили, но для которых ещё не нашли закрывающую.
elif ch in closing – если символ – закрывающая скобка (), ] или }), нам нужно найти соответствующую открывающую.
Сначала проверяем, не пуст ли стек. 
Если пуст – значит перед этой закрывающей скобкой не было открывающей, 
например строка начинается с } – сразу возвращаем False.
Затем извлекаем верхний элемент стека (pop). 
Это должна быть последняя открывающая скобка, которую мы ещё не закрыли.
Сравниваем эту открывающую скобку с парой для текущей закрывающей (словарь pairs). 
Например, для ) пара – (, для ] – [, для } – {.
Если не совпадают (например, в стеке лежала [, а мы встретили )), значит скобки неправильно вложены – возвращаем False.
После обработки всех символов проверяем, пуст ли стек. 
Если в нём остались открывающие скобки (например, строка заканчивается на (), 
значит они не были закрыты – строка несбалансирована. 
Если стек пуст – все открывающие нашли свои закрывающие в правильном порядке.
"""

if __name__ == "__main__":
    # Примеры из условия
    test_strings = [
        "(((([{}]))))",
        "[([])((([[[]]])))]{()}",
        "{{[()]}}",
        "}{}",
        "{{[(])]}}",
        "[[{())}]"
    ]

    print("=== Проверка примеров ===")
    for s in test_strings:
        print(f"{s:30} -> {is_balanced(s)}")

    print("\n=== Ввод пользователя ===")
    user_input = input("Введите строку со скобками: ")
    print(is_balanced(user_input))
