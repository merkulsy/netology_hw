"""
Стек — абстрактный тип данных, представляющий список элементов, организованных по принципу LIFO (англ. last in — first out, «последним пришёл — первым вышел»). Чаще всего принцип работы стека сравнивают со стопкой тарелок: чтобы взять вторую сверху, нужно снять верхнюю. Или с магазином в огнестрельном оружии: стрельба начнётся с патрона, заряженного последним.

Нужно реализовать класс Stack со следующими методами:
is_empty — проверка стека на пустоту. Метод возвращает True или False;
push — добавляет новый элемент на вершину стека. Метод ничего не возвращает;
pop — удаляет верхний элемент стека. Стек изменяется. Метод возвращает верхний элемент стека;
peek — возвращает верхний элемент стека, но не удаляет его. Стек не меняется;
size — возвращает количество элементов в стеке.
"""


class Stack:
    def __init__(self):
        self._items = []          # внутреннее хранилище

    def is_empty(self):
        """Проверка на пустоту. Возвращает True, если стек пуст."""
        return len(self._items) == 0

    def push(self, item):
        """Добавляет элемент на вершину стека."""
        self._items.append(item)

    def pop(self):
        """Удаляет и возвращает верхний элемент стека.
           Вызывает ошибку, если стек пуст"""
        if self.is_empty():
            raise IndexError("pop from empty stack")
        return self._items.pop()

    def peek(self):
        """Возвращает верхний элемент без удаления."""
        if self.is_empty():
            raise IndexError("peek from empty stack")
        return self._items[-1]

    def size(self):
        """Возвращает количество элементов в стеке."""
        return len(self._items)


if __name__ == "__main__":

    # Создаём стек
    s = Stack()

    # Проверяем, пуст ли он
    print(s.is_empty())          # True

    # Добавляем элементы (push)
    s.push(10)
    s.push(20)
    s.push("hello")
    s.push([1, 2, 3])

    # Смотрим размер и вершину
    print(s.size())              # 4
    print(s.peek())              # [1, 2, 3]  (верхний элемент, стек не меняется)
    print(s.size())              # 4 (размер остался прежним)

    # Удаляем верхний элемент (pop)
    top = s.pop()
    print(top)                   # [1, 2, 3]
    print(s.size())              # 3
    print(s.peek())              # "hello"

    # Удаляем все элементы
    while not s.is_empty():
        print(f"Извлекаем: {s.pop()}")   # выведет "hello", 20, 10

    print(s.is_empty())          # True

    # Попытка вызвать pop или peek на пустом стеке – получим исключение
    try:
        s.pop()
    except IndexError as e:
        print("Ошибка:", e)      # "pop from empty stack"