"""
Используя стек из задания 1, решите задачу на проверку сбалансированности скобок. Сбалансированность скобок означает,
что каждый открывающий символ имеет соответствующий ему закрывающий, и пары скобок правильно вложены друг в друга.
Пример сбалансированных последовательностей скобок:
(((([{}]))))
[([])((([[[]]])))]{()}
{{[()]}}
Несбалансированные последовательности:
}{}
{{[(])]}}
[[{())}]
Программа ожидает на вход строку со скобками.
На выход сообщение: «Сбалансированно», если строка корректная, и «Несбалансированно», если строка составлена неверно.
"""

from hw1_stack import Stack

def is_balanced(text: str) -> bool:
    """
    Проверяет, сбалансированы ли скобки в строке.
    Учитываются три вида скобок: (), [], {}.
    Все остальные символы игнорируются.
    """
    stack = Stack()
    opening = "([{"
    closing = ")]}"
    pairs = {')': '(', ']': '[', '}': '{'}   # соответствие закрывающей → открывающей

    for ch in text:                          # перебираем все символы строки
        if ch in opening:                    # если это открывающая скобка
            stack.push(ch)                   # кладём её на стек (ждём закрывающую)
        elif ch in closing:                  # если это закрывающая скобка
            # если стек пуст — значит закрывающая скобка не имеет пары
            if stack.is_empty():
                return False
            # снимаем верхнюю открывающую скобку
            top = stack.pop()
            # проверяем, соответствует ли она текущей закрывающей
            if top != pairs[ch]:
                return False                 # не совпадают → неправильный порядок
        # остальные символы (буквы, цифры, знаки) просто игнорируем

    # Если после обработки всех символов стек пуст — все скобки закрыты правильно
    return stack.is_empty()


if __name__ == "__main__":
    # Примеры из условия
    test_strings = [
        "(((([{}]))))",
        "[([])((([[[]]])))]{()}",
        "{{[()]}}",
        "}{}",
        "{{[(])]}}",
        "[[{())}]"
    ]

    print("=== Проверка примеров ===")
    for s in test_strings:
        result = "Сбалансированно" if is_balanced(s) else "Несбалансированно"
        print(f"{s:30} -> {result}")

    print("\n=== Ввод пользователя ===")
    user_input = input("Введите строку со скобками: ")
    if is_balanced(user_input):
        print("Сбалансированно")
    else:
        print("Несбалансированно")
